# Integer
jumlah_buku = 12
print(jumlah_buku, type(jumlah_buku))

# Float
tinggi = 158.5
print(tinggi, type(tinggi))

# String
nama = "Sesilia"
print(nama, type(nama))

# Boolean
is_active = True
print(is_active, type(is_active))

# List
buah = ["apel", "jeruk", "mangga"]
print(buah, type(buah))

# Tuple
warna = ("merah", "hijau", "biru")
print(warna, type(warna))

# Dictionary
siswa = {"nama": "Sesilia", "sekolah": "SMKN 2 Subang", "kota": "Subang"}
print(siswa, type(siswa))

# Set
angka = {1, 2, 2, 3, 3, 3}
print(angka, type(angka))
